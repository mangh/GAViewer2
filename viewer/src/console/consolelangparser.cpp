/*
Hand-written lexer and recursive descent parser for the GAViewer console
language. It replaces the parser generated by ANTLR 2 from ConsoleLexer.g and
ConsoleParser.g and reproduces its tokenization and the statement trees it
built; only syntax error recovery differs (see Parser::input()).

Grammar (EBNF; terminals in capitals or quotes):

  input       = { stmt } EOF ;
  stmtlist    = { stmt } ;
  stmt        = exprlist ( "," | ";" )            (* "," : verbose, display the result *)
              | ";" | ","                         (* dummy statement *)
              | "{" stmtlist "}"
              | "return" exprlist ";"
              | "break" ";" | "continue" ";" | "suspend" ";"
              | "dynamic" "{" [ IDENTIFIER ":" ] stmtlist "}"
              | "inner_product" "(" FUNCNAME ")"
              | "default_model" "(" [ model ] ")"
              | "variable" funcdefname ";"
              | "while" "(" exprlist ")" stmt
              | "for" "(" exprlist ";" exprlist ";" exprlist ")" stmt
              | "if" "(" exprlist ")" stmt [ "else" stmt ]
              | "switch" "(" exprlist ")" "{" { case } "}"
              | ( "function" | "batch" ) funcdefname "(" [ argspec { "," argspec } ] ")" ( "{" stmtlist "}" | ";" ) ;
  case        = ( "case" exprlist | "default" ) ":" stmtlist ;
  exprlist    = { expr } ;                        (* operators are resolved later, see consoleExprListStmt *)
  expr        = CONSTANT
              | [ "::" ] IDENTIFIER { "[" exprlist "]" }
              | [ "::" ] FUNCNAME "(" [ exprlist { "," exprlist } ] ")"
              | OPERATOR expr
              | "(" exprlist ")"
              | "(" model ")" expr ;              (* cast *)
  argspec     = [ model ] funcdefname ;
  funcdefname = IDENTIFIER | FUNCNAME ;
  model       = "e3ga" | "p3ga" | "c3ga" | "c5ga" | "i2ga" ;

Lexical structure:

  - whitespace (' ', '\t', '\r', '\n') and comments ("//...", "/ * ... * /") separate tokens,
  - OPERATOR: a sequence of the characters  < > ! = . + - & | ^ ~ * /  and whitespace
    (so "+ -" is one token; '/' only if not starting a comment), the text is passed
    to consoleStatement::setOp() which splits it into a binary and unary operators,
  - CONSTANT: digits [ "." digits ] [ ( "e" | "E" ) [ "+" | "-" ] digits ]  ("3e1" is 30),
    a leading '.' starts an OPERATOR,
  - identifiers: [A-Za-z_][A-Za-z0-9_]*, or a quoted string "..." (\" is a quote);
    keywords and the model names are recognized in both forms; an unquoted
    identifier that names a function in the current parsing scope is a FUNCNAME,
  - "::" (global scope), ':', ';', ',', '(', ')', '[', ']', '{', '}'.
*/

