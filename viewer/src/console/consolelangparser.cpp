enum class Tok
{
    Eof,
    Identifier,
    FuncName,
    E3ga,
    P3ga,
    C3ga,
    C5ga,
    I2ga,
    Return,
    Switch,
    Default,
    Case,
    Break,
    Continue,
    Suspend,
    If,
    Else,
    While,
    For,
    Function,
    Batch,
    Dynamic,
    InnerProduct,
    DefaultModel,
    Variable,
    Operator,
    Constant,
    Colon,
    Semicolon,
    Comma,
    ParOpen,
    ParClose,
    SquareOpen,
    SquareClose,
    CurlyOpen,
    CurlyClose,
    Global,
};

// names as used in error messages (the ANTLR paraphrases)
const char *tokName(Tok t)
{
    switch (t)
    {
    case Tok::Eof:
        return "end of file";
    case Tok::Identifier:
        return "an identifier";
    case Tok::FuncName:
        return "a function";
    case Tok::E3ga:
    case Tok::P3ga:
    case Tok::C3ga:
    case Tok::C5ga:
    case Tok::I2ga:
        return "a model name";
    case Tok::Operator:
        return "operator";
    case Tok::Constant:
        return "a constant scalar";
    case Tok::Colon:
        return ":";
    case Tok::Semicolon:
        return ";";
    case Tok::Comma:
        return ",";
    case Tok::ParOpen:
        return "(";
    case Tok::ParClose:
        return ")";
    case Tok::SquareOpen:
        return "[";
    case Tok::SquareClose:
        return "]";
    case Tok::CurlyOpen:
        return "{";
    case Tok::CurlyClose:
        return "}";
    case Tok::Global:
        return "::";
    default:
        return "a keyword";
    }
}

struct Keyword
{
    const char *text;
    Tok type;
};

const Keyword c_keywords[] = {
    {"return", Tok::Return},
    {"switch", Tok::Switch},
    {"default", Tok::Default},
    {"case", Tok::Case},
    {"break", Tok::Break},
    {"continue", Tok::Continue},
    {"suspend", Tok::Suspend},
    {"if", Tok::If},
    {"else", Tok::Else},
    {"while", Tok::While},
    {"for", Tok::For},
    {"function", Tok::Function},
    {"batch", Tok::Batch},
    {"dynamic", Tok::Dynamic},
    {"inner_product", Tok::InnerProduct},
    {"default_model", Tok::DefaultModel},
    {"variable", Tok::Variable},
    {"e3ga", Tok::E3ga},
    {"p3ga", Tok::P3ga},
    {"c3ga", Tok::C3ga},
    {"c5ga", Tok::C5ga},
    {"i2ga", Tok::I2ga},
};

bool isModel(Tok t)
{
    return (t == Tok::E3ga) || (t == Tok::P3ga) || (t == Tok::C3ga) || (t == Tok::C5ga) || (t == Tok::I2ga);
}

// FIRST(expr)
bool startsExpr(Tok t)
{
    return (t == Tok::Constant) || (t == Tok::Identifier) || (t == Tok::FuncName) || (t == Tok::Operator) ||
           (t == Tok::ParOpen) || (t == Tok::Global);
}

// FIRST(stmt)
bool startsStmt(Tok t)
{
    switch (t)
    {
    case Tok::Semicolon:
    case Tok::Comma:
    case Tok::CurlyOpen:
    case Tok::Return:
    case Tok::Break:
    case Tok::Continue:
    case Tok::Suspend:
    case Tok::Dynamic:
    case Tok::InnerProduct:
    case Tok::DefaultModel:
    case Tok::Variable:
    case Tok::While:
    case Tok::For:
    case Tok::If:
    case Tok::Switch:
    case Tok::Function:
    case Tok::Batch:
        return true;
    default:
        return startsExpr(t);
    }
}

struct Token
{
    Tok type = Tok::Eof;
    std::string text;
    int line = 0;
    int column = 0;
};

// A syntax (or lexical) error; the message is complete except for the position.
struct ParseError
{
    int line;
    int column;
    std::string message;
};

// ---------------------------------------------------------------------------
// lexer
// ---------------------------------------------------------------------------

class Lexer
{
  public:
    // 'scope' is the current parsing scope of the parser: it is consulted (at
    // the moment a token is lexed) to tell function names from identifiers.
    Lexer(std::string_view source, consoleScope *const &scope) : m_src(source), m_scope(scope)
    {
    }

    Token next();

  private:
    static constexpr int EOF_CHAR = -1;
    static constexpr int TAB_SIZE = 8;

    std::string_view m_src;
    consoleScope *const &m_scope;
    size_t m_pos = 0;
    int m_line = 1;
    int m_column = 1;

    // characters outside '\3'..'\377' are not part of the vocabulary
    static bool inVocabulary(int c)
    {
        return (c >= 3) && (c <= 255);
    }
    static bool isWs(int c)
    {
        return (c == ' ') || (c == '\t') || (c == '\r') || (c == '\n');
    }
    static bool isDigit(int c)
    {
        return (c >= '0') && (c <= '9');
    }
    static bool isIdStart(int c)
    {
        return ((c >= 'a') && (c <= 'z')) || ((c >= 'A') && (c <= 'Z')) || (c == '_');
    }
    static bool isIdChar(int c)
    {
        return isIdStart(c) || isDigit(c);
    }
    static bool isOpChar(int c)
    {
        return (c > 0) && (c < 128) && (std::strchr("<>!=.+-&|^~*", c) != NULL);
    }

    int la(size_t k) const
    {
        size_t p = m_pos + k - 1;
        return (p < m_src.size()) ? static_cast<unsigned char>(m_src[p]) : EOF_CHAR;
    }
    void consume()
    {
        if (la(1) == '\t')
            m_column = (((m_column - 1) / TAB_SIZE) + 1) * TAB_SIZE + 1;
        else
            m_column++;
        m_pos++;
    }
    void newline()
    {
        m_line++;
        m_column = 1;
    }
    // consumes one character, appending it to 'text'
    void take(std::string &text)
    {
        text += static_cast<char>(la(1));
        consume();
    }

    static std::string charName(int c)
    {
        if (c == EOF_CHAR)
            return "end of file";
        char buf[16];
        if ((c >= 32) && (c < 127))
            std::snprintf(buf, sizeof(buf), "'%c'", c);
        else
            std::snprintf(buf, sizeof(buf), "0x%02X", c);
        return buf;
    }
    [[noreturn]] void error(const std::string &message) const
    {
        throw ParseError{m_line, m_column, message};
    }

    void whitespace(std::string *text);
    void multiLineComment();
    void singleLineComment();
    Token operatorToken(int line, int column);
    Token constant(int line, int column);
    void digits(std::string &text, int line, int column, const char *what);
    Token identifier(int line, int column);
};

void Lexer::whitespace(std::string *text)
{
    int c = la(1);
    if (text)
        *text += static_cast<char>(c);
    consume();
    if (c == '\n')
        newline();
}

void Lexer::multiLineComment()
{
    consume(); // '/'
    consume(); // '*'
    for (;;)
    {
        int c = la(1);
        if ((c == '*') && inVocabulary(la(2)) && (la(2) != '/'))
            consume();
        else if (c == '\n')
        {
            consume();
            newline();
        }
        else if (inVocabulary(c) && (c != '*'))
            consume();
        else
            break;
    }
    if ((la(1) != '*') || (la(2) != '/'))
        error("expecting '*/', found " + charName(la(1)));
    consume();
    consume();
}

void Lexer::singleLineComment()
{
    consume(); // '/'
    consume(); // '/'
    while (inVocabulary(la(1)) && (la(1) != '\n'))
        consume();
}

Token Lexer::operatorToken(int line, int column)
{
    Token t{Tok::Operator, std::string(), line, column};
    for (;;)
    {
        int c = la(1);
        if (isOpChar(c))
            take(t.text);
        else if (isWs(c))
            whitespace(&t.text);
        else if ((c == '/') && (la(2) != '*') && (la(2) != '/'))
            take(t.text);
        else
            break;
    }
    return t;
}

// Reads one or more digits of the number starting at line:column; 'what' tells
// which part of the number the digits belong to (for the error message).
void Lexer::digits(std::string &text, int line, int column, const char *what)
{
    if (!isDigit(la(1)))
        throw ParseError{line, column,
                         "malformed number '" + text + "': expecting a digit " + what + ", found " +
                             charName(la(1))};
    while (isDigit(la(1)))
        take(text);
}

Token Lexer::constant(int line, int column)
{
    Token t{Tok::Constant, std::string(), line, column};
    digits(t.text, line, column, "");
    if (la(1) == '.')
    {
        take(t.text);
        digits(t.text, line, column, "after the decimal point");
    }
    if ((la(1) == 'e') || (la(1) == 'E'))
    {
        take(t.text);
        if ((la(1) == '+') || (la(1) == '-'))
            take(t.text);
        digits(t.text, line, column, "in the exponent");
    }
    return t;
}

Token Lexer::identifier(int line, int column)
{
    std::string text;
    bool inQuotes = (la(1) == '"');
    if (inQuotes)
    {
        take(text);
        for (;;)
        {
            int c = la(1);
            if ((c == '\\') && (la(2) == '"'))
            {
                consume();
                consume();
                text += '"';
            }
            else if (inVocabulary(c) && (c != '\n') && (c != '"'))
                take(text);
            else
                break;
        }
        if ((la(1) == '"') || (la(1) == '\n'))
            take(text);
        if (text.back() != '"')
        {
            cprintf("Warning line(%d, %d): newline or end of file in quoted string\n", m_line, m_column);
            newline(); // it doesn't matter whether this EOF or newline, just up the line #
        }
        // strip the quotes (or the opening quote and the last character, if not terminated by a quote)
        text = (text.size() > 2) ? text.substr(1, text.size() - 2) : std::string();
    }
    else
    {
        while (isIdChar(la(1)))
            take(text);
    }

    Token t{Tok::Identifier, std::move(text), line, column};
    for (const Keyword &kw : c_keywords)
    {
        if (t.text == kw.text)
        {
            t.type = kw.type; // keywords and model names are recognized also when quoted
            return t;
        }
    }
    if ((!inQuotes) && m_scope->isFunction(t.text))
        t.type = Tok::FuncName;
    return t;
}

Token Lexer::next()
{
    for (;;)
    {
        const int line = m_line, column = m_column;
        const int c = la(1);

        auto single = [&](Tok type) {
            Token t{type, std::string(1, static_cast<char>(c)), line, column};
            consume();
            return t;
        };

        switch (c)
        {
        case ';':
            return single(Tok::Semicolon);
        case ',':
            return single(Tok::Comma);
        case '(':
            return single(Tok::ParOpen);
        case ')':
            return single(Tok::ParClose);
        case '[':
            return single(Tok::SquareOpen);
        case ']':
            return single(Tok::SquareClose);
        case '{':
            return single(Tok::CurlyOpen);
        case '}':
            return single(Tok::CurlyClose);
        default:
            break;
        }

        if (isIdStart(c) || (c == '"'))
            return identifier(line, column);
        if ((c == '/') && (la(2) == '*'))
        {
            multiLineComment();
            continue;
        }
        if ((c == '/') && (la(2) == '/'))
        {
            singleLineComment();
            continue;
        }
        if ((c == ':') && (la(2) == ':'))
        {
            consume();
            consume();
            return Token{Tok::Global, "::", line, column};
        }
        if (isWs(c))
        {
            whitespace(NULL);
            continue;
        }
        if (isOpChar(c) || (c == '/'))
            return operatorToken(line, column);
        if (c == ':')
            return single(Tok::Colon);
        if (isDigit(c))
            return constant(line, column);
        if (c == EOF_CHAR)
            return Token{Tok::Eof, std::string(), line, column};

        consume(); // skip the offending character, so that error recovery makes progress
        throw ParseError{line, column, "unexpected char: " + charName(c)};
    }
}

