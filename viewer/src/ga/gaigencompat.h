#ifndef _GA_GAIGENCOMPAT_H_
#define _GA_GAIGENCOMPAT_H_

/*
TRANSITIONAL: the ga:: operations (see algorithms.h, format.h) for the Gaigen
algebras that have not been replaced by Garamon yet, forwarding to their
members. Code that is written for every algebra (e.g. the console functions
in consolealgebrafunctions.cpp) uses the ga:: operations only, so that it
works with both kinds of multivector. Remove this file when the last Gaigen
algebra is gone.
*/

#include <string>
#include <vector>

#include "../gaincludes.h" // the Gaigen algebras (and their free functions ::gp, ...)
#include "algorithms.h" // IWYU pragma: export

namespace ga
{

// a Gaigen multivector type (e3ga, p3ga, ... generated by Gaigen 1)
template <class MV>
concept gaigenMV = requires(const MV &a) {
    a.gradeUsage();
    a.norm_a();
};

template <gaigenMV MV> double scalar(const MV &a)
{
    return a.scalar();
}
template <gaigenMV MV> double norm_a(const MV &a)
{
    return a.norm_a();
}
template <gaigenMV MV> double norm_b(const MV &a)
{
    return a.norm_b();
}
template <gaigenMV MV> int largestGrade(const MV &a)
{
    return a.largestGrade();
}
template <gaigenMV MV> MV takeGrade(const MV &a, unsigned gradeMask)
{
    return a((int)gradeMask);
}

template <gaigenMV MV> MV reverse(const MV &a)
{
    return a.reverse();
}
template <gaigenMV MV> MV gradeInvolution(const MV &a)
{
    return a.gradeInvolution();
}
template <gaigenMV MV> MV cliffordConjugate(const MV &a)
{
    return a.cliffordConjugate();
}
template <gaigenMV MV> MV negate(const MV &a)
{
    return a.negate();
}
template <gaigenMV MV> MV dual(const MV &a)
{
    return a.dual();
}
template <gaigenMV MV> MV inverse(const MV &a)
{
    return a.inverse();
}
template <gaigenMV MV> MV generalInverse(const MV &a)
{
    return a.generalInverse();
}
template <gaigenMV MV> MV exp(const MV &a, int order = 9)
{
    return a.exp(order);
}

template <gaigenMV MV> MV gp(const MV &a, const MV &b)
{
    return ::gp(a, b);
}
template <gaigenMV MV> MV op(const MV &a, const MV &b)
{
    return ::op(a, b);
}
template <gaigenMV MV> MV lcont(const MV &a, const MV &b)
{
    return ::lcont(a, b);
}
template <gaigenMV MV> MV rcont(const MV &a, const MV &b)
{
    return ::rcont(a, b);
}
template <gaigenMV MV> MV scp(const MV &a, const MV &b)
{
    return ::scp(a, b);
}
template <gaigenMV MV> MV hip(const MV &a, const MV &b)
{
    return ::hip(a, b);
}
template <gaigenMV MV> MV mhip(const MV &a, const MV &b)
{
    return ::mhip(a, b);
}
template <gaigenMV MV> MV igp(const MV &a, const MV &b)
{
    return ::igp(a, b);
}
template <gaigenMV MV> MV gpem(const MV &a, const MV &b)
{
    return ::gpem(a, b);
}
template <gaigenMV MV> MV lcem(const MV &a, const MV &b)
{
    return ::lcem(a, b);
}
template <gaigenMV MV> MV meet(const MV &a, const MV &b)
{
    return ::meet(a, b);
}
template <gaigenMV MV> MV join(const MV &a, const MV &b)
{
    return ::join(a, b);
}

template <gaigenMV MV> MV project(const MV &blade, const MV &a)
{
    MV r;
    r.project(blade, a);
    return r;
}
template <gaigenMV MV> MV reject(const MV &blade, const MV &a)
{
    MV r;
    r.reject(blade, a);
    return r;
}

template <gaigenMV MV> int mvType(const MV &a, int *gradeMask = nullptr)
{
    return a.mvType(gradeMask);
}

template <gaigenMV MV> int factor(const MV &a, std::vector<MV> &factors)
{
    MV f[8];
    int n = a.factor(f);
    factors.assign(f, f + n);
    return n;
}

// basis vector 'i' (in the order of the Gaigen basis)
template <gaigenMV MV> MV basisVector(int i)
{
    MV r;
    r.copy(*MV::bv[i]);
    return r;
}

template <gaigenMV MV> std::string toString(const MV &a, const char *fp = "%2.2f")
{
    return a.string(fp);
}

} // namespace ga

#endif /* _GA_GAIGENCOMPAT_H_ */
